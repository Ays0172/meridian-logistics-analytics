"""Append one day of new data, without ever touching what is already there.

    python live_feed.py                  # catch up from the watermark to today
    python live_feed.py --until 2026-09-30
    python live_feed.py --redo 2026-08-25
    python live_feed.py --status

The frozen history (2021-08-21 to 2026-08-20) is produced by build_facts.py and
is never modified by this script. Everything after it arrives here, one day at a
time.

Four properties, and each one is a deliberate design choice rather than a
side effect:

**Append-only.** Every write uses ``mode="append"``, which allocates a new
``part-NNN.parquet`` inside the month partition and never opens an existing
file. Yesterday's rows are not "unlikely" to change — the code has no path that
could change them.

**Watermark-driven.** ``_state/watermark.json`` records the last date appended.
The next run generates from watermark+1 to today. So if the history ends at row
10, tomorrow starts at 11, and a run that fires twice in one day is a no-op the
second time.

**Per-day seeding.** Each day's rows come from ``child_rng("live:<table>:<date>")``
— derived from the date, not from run order or from how many runs came before.
That means a given calendar day always produces the same rows no matter when it
is generated, a missed day can be backfilled later and still be correct, and the
whole feed stays reproducible.

**Reversible.** Every run records the exact files it wrote. ``--redo DATE``
deletes precisely those files and regenerates that day. Nothing else is touched.

Surrogate keys continue from where history stopped, tracked per table in the
watermark, so no key is ever reused.
"""

